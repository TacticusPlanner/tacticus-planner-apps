import { describe, expect, it } from "vitest"

import npcGaps from "../../../../../public/locales/en/npcAbilityTextGaps.json"
import raidBossGaps from "../../../../../public/locales/en/raidBossAbilityTextGaps.json"

type Entry = {
  description: string
  variables: Record<string, (string | number)[]>
  constants: Record<string, string>
  scaled: string[]
}

// One file per ability: `locales/<lng>/npcAbilityText/<id>.json` holding `{ "<id>": entry }`.
const npcFiles = import.meta.glob<Record<string, Entry>>(
  "../../../../../public/locales/*/npcAbilityText/*.json",
  { eager: true, import: "default" }
)
const raidBossFiles = import.meta.glob<Record<string, Entry>>(
  "../../../../../public/locales/*/raidBossAbilityText/*.json",
  { eager: true, import: "default" }
)

const fileParts = (path: string) => {
  const match = /\/locales\/([^/]+)\/[^/]+\/([^/]+)\.json$/.exec(path)
  if (!match?.[1] || !match[2]) throw new Error(`unexpected path ${path}`)
  return { locale: match[1], id: match[2] }
}

/** locale -> id -> entry, from each file's own entry. */
function tablesOf(files: Record<string, Record<string, Entry>>) {
  const tables: Record<string, Record<string, Entry>> = {}
  for (const [path, content] of Object.entries(files)) {
    const { locale, id } = fileParts(path)
    const entry = content[id]
    if (entry) (tables[locale] ??= {})[id] = entry
  }
  return tables
}

const locales = tablesOf(npcFiles)
const en = locales.en ?? {}
const de = locales.de ?? {}

function entryOf(locale: Record<string, Entry>, id: string): Entry {
  const entry = locale[id]
  if (!entry) throw new Error(`missing ability text ${id}`)
  return entry
}

const DAMAGE_PROFILE_TYPE = /^DamageProfileType(Style)?(_\d+)?$/
const trimmedHas = (rec: Record<string, unknown>, key: string) =>
  rec[key] !== undefined || Object.keys(rec).some((k) => k.trim() === key)

// Token names without a split index: `{[dmg[0]]}` references the variable `dmg`.
const placeholders = (text: string) => [
  ...new Set(
    [...text.matchAll(/\{\[(.+?)\]\}/g)].map((m) =>
      (m[1] ?? "").replace(/\[\d+\]$/, "")
    )
  ),
]

describe("Ability rules text", () => {
  it("stores each ability in its own file, holding exactly that ability", () => {
    for (const [path, content] of Object.entries({
      ...npcFiles,
      ...raidBossFiles,
    })) {
      expect(Object.keys(content), path).toEqual([fileParts(path).id])
    }
  })

  it("covers the same abilities in every locale", () => {
    const enKeys = Object.keys(en).sort()
    expect(enKeys.length).toBeGreaterThan(50)
    expect(Object.keys(locales).sort()).toEqual(["de", "en", "es", "fr"])

    for (const [code, locale] of Object.entries(locales)) {
      const missing = enKeys.filter((id) => !locale[id])
      const extra = Object.keys(locale).filter((id) => !en[id])
      expect({ missing, extra }, code).toEqual({ missing: [], extra: [] })
    }
  })

  it("shares one set of value tables per ability across locales", () => {
    for (const [code, locale] of Object.entries(locales)) {
      for (const [id, entry] of Object.entries(locale)) {
        const english = entryOf(en, id)
        expect(
          [entry.variables, entry.constants, entry.scaled],
          `${code}:${id}`
        ).toEqual([english.variables, english.constants, english.scaled])
      }
    }
  })

  it("resolves every placeholder from the entry's own variable and constant tables", () => {
    for (const [code, locale] of Object.entries(locales)) {
      for (const [id, entry] of Object.entries(locale)) {
        const missing = placeholders(entry.description).filter((name) => {
          if (name === "UnitName" || name.startsWith("S/")) return false
          if (trimmedHas(entry.variables, name)) return false
          if (trimmedHas(entry.constants, name)) return false
          const match = DAMAGE_PROFILE_TYPE.exec(name)
          if (match)
            return !trimmedHas(
              entry.constants,
              `damageProfile${match[2] ?? ""}`
            )
          return true
        })
        expect(missing, `${code}:${id}`).toEqual([])
      }
    }
  })

  it("covers every catalog ability with complete source text", () => {
    // Generated by scripts/generate-ability-text-i18n.mjs from the 1.43 catalog and V1 develop: NPC,
    // character, relic and MoW (primary, secondary, mythic) abilities. The generator lists the ids it
    // leaves out (4 NPC placeholders) in npcAbilityTextGaps, which the client never requests.
    expect(Object.keys(en).length).toBe(434)
    expect(npcGaps).toEqual([
      "BossEndFightUndefeated",
      "RepairEnthusiast",
      "RunsAround",
      "RunsAway",
    ])
    for (const [code, locale] of Object.entries(locales)) {
      expect(
        npcGaps.filter((id) => locale[id]),
        code
      ).toEqual([])
    }
  })

  it("carries relic and Machine of War rules text", () => {
    expect(
      entryOf(en, "AmuletOfTheVoidwyrm").variables.critDmgReduction
    ).toEqual([390, 411, 432, 453, 474, 495, 516, 537, 558, 579])
    expect(
      entryOf(en, "WisdomOfTheAncients").variables.dmgReductionPct
    ).toEqual([10, 13, 16, 20])
    // V1 keys these constants with a trailing space; the renderer looks them up trimmed.
    expect(entryOf(en, "ReanimationBeam").constants).toMatchObject({
      "initialCooldownTurns ": "1",
      "munitionsCost ": "1",
    })
    expect(entryOf(de, "DutyEternal").description).not.toBe(
      entryOf(en, "DutyEternal").description
    )
    expect(entryOf(en, "SlashingDive").variables.dmg).toHaveLength(65)
  })

  it("carries per-level variable tables and real localized text", () => {
    const entry = entryOf(en, "AdaptiveStrategy")
    expect(entry.variables.minDmg?.length).toBeGreaterThan(20)
    expect(entry.variables.minDmg?.[0]).toBe(12)
    expect(entryOf(de, "AdaptiveStrategy").description).not.toBe(
      entry.description
    )
  })

  it("stores no variables the description never references", () => {
    for (const entry of Object.values(en)) {
      const used = new Set(placeholders(entry.description))
      expect(
        Object.keys(entry.variables).filter((k) => !used.has(k.trim()))
      ).toEqual([])
    }
  })
})

describe("Raid-boss ability rules text", () => {
  const tables = tablesOf(raidBossFiles)

  it("covers the same abilities in every locale, with no file for a listed gap", () => {
    expect(Object.keys(tables).sort()).toEqual(["de", "en", "es", "fr"])
    const enKeys = Object.keys(tables.en ?? {}).sort()
    expect(enKeys.length).toBe(152)
    for (const [code, locale] of Object.entries(tables)) {
      expect(Object.keys(locale).sort(), code).toEqual(enKeys)
      expect(
        raidBossGaps.filter((id) => locale[id]),
        code
      ).toEqual([])
    }
  })
})
